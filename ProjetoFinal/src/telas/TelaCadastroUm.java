    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        String nome = txtNome.getText().trim();
        String cpf = txtCpf.getText().replaceAll("[^0-9]", "");
        String telefone = txtTelefone.getText().replaceAll("[^0-9]", "");
        String email = txtEmail.getText().trim();
        String nascimento = txtNasc.getText().trim();
        String moradia = txtMoradia.getText().trim();

        String rua = txtRua.getText().trim();
        String numero = txtNumero.getText().trim();
        String bairro = txtbairro.getText().trim();
        String cidade = txtCidade.getText().trim();
        String estado = cmbEstado.getSelectedItem().toString();
        String cep = txtCep.getText().replaceAll("[^0-9]", "");

        String login = txtLogin.getText().trim();
        String senha = new String(txtSenha.getPassword());
        String confirmarSenha = new String(txtConfirmSenha.getPassword());

        if (nome.isEmpty() || cpf.isEmpty()
                || telefone.isEmpty() || email.isEmpty()
                || nascimento.isEmpty() || moradia.isEmpty()
                || rua.isEmpty() || numero.isEmpty()
                || bairro.isEmpty() || cidade.isEmpty()
                || estado.equals("Selecione") || cep.isEmpty()
                || login.isEmpty() || senha.trim().isEmpty()
                || confirmarSenha.trim().isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Preencha todos os campos!");
            return;
        }

        if (cpf.length() != 11 || cep.length() != 8
                || telefone.length() != 11) {

            JOptionPane.showMessageDialog(this,
                    "Verifique o CPF, CEP e telefone!");
            return;
        }

        if (!senha.equals(confirmarSenha)) {
            JOptionPane.showMessageDialog(this,
                    "As senhas não coincidem!");
            return;
        }

        LocalDate dataNascimento;

        try {
            DateTimeFormatter formato
                    = DateTimeFormatter.ofPattern("dd/MM/uuuu")
                            .withResolverStyle(ResolverStyle.STRICT);

            dataNascimento = LocalDate.parse(nascimento, formato);

        } catch (DateTimeParseException e) {
            JOptionPane.showMessageDialog(this,
                    "Data de nascimento inválida!");
            return;
        }

        int idade = Period.between(
                dataNascimento, LocalDate.now()).getYears();

        if (idade < 18) {
            JOptionPane.showMessageDialog(this,
                    "É necessário ter pelo menos 18 anos para se cadastrar.");
            return;
        }

        Endereco endereco = new Endereco(
                0,
                rua,
                numero,
                bairro,
                cidade,
                estado,
                cep
        );

        Cliente cliente = new Cliente(
                dataNascimento.toString(),
                moradia,
                0,
                nome,
                cpf,
                telefone,
                email,
                endereco
        );

        CadastroService cadastro = new CadastroService();

        boolean sucesso = cadastro.cadastrarCliente(
                cliente, login, senha);

        if (sucesso) {
            JOptionPane.showMessageDialog(this,
                    "Cadastro realizado com sucesso!");

            new TelaLoginUm().setVisible(true);
            dispose();

        } else {
            JOptionPane.showMessageDialog(this,
                    "Não foi possível realizar o cadastro. "
                    + "Verifique se o CPF ou login já está cadastrado.");
        }

    }//GEN-LAST:event_btnCadastrarActionPerformed

