    public TelaAdocaoTeste(Usuario usuario) {
        initComponents();
        this.usuario = usuario;

        Dimension tela = Toolkit.getDefaultToolkit().getScreenSize();

        int largura = (int) (tela.width * 0.90);
        int altura = (int) (tela.height * 0.90);

        setSize(largura, altura);
        setLocationRelativeTo(null);

        // Organizar os cartões em 5 colunas
        painelAnimais.setLayout(
                new java.awt.GridLayout(0, 5, 15, 15)
        );

        // Deixar a área transparente
        painelAnimais.setOpaque(false);
        scrollAnimais.setOpaque(false);
        scrollAnimais.getViewport().setOpaque(false);
        scrollAnimais.setBorder(null);
        scrollAnimais.setViewportBorder(null);
        painelAnimais.setBorder(null);

        AnimalDAO dao = new AnimalDAO();

        ArrayList<Animal> animais = dao.consultarDisponiveis();

        painelAnimais.removeAll();

        for (Animal animal : animais) {
            CardAnimal card = new CardAnimal(animal, usuario);
            painelAnimais.add(card);
        }

        painelAnimais.revalidate();
        painelAnimais.repaint();

    }

