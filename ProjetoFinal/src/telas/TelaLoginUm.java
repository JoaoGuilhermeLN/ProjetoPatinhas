    private void btnEntrar1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEntrar1ActionPerformed
        String usuarioLogin = login.getText().trim();
        String senha = new String(txtSenha.getPassword());

        AutenticacaoService autenticacao = new AutenticacaoService();

        Usuario usuario = autenticacao.autenticar(usuarioLogin, senha);

        if (usuario == null) {
            JOptionPane.showMessageDialog(this, "Login ou senha incorretos!");
        } else {
            if (usuario.getPerfil().equals("FUNCIONARIO")) {
                new areaAdministrativa().setVisible(true);
                dispose();
            } else if (usuario.getPerfil().equals("CLIENTE")) {
                new telaAdocao(usuario).setVisible(true);
                dispose();
            }
        }
    }//GEN-LAST:event_btnEntrar1ActionPerformed

