    private void carregarFoto(String caminho) {

        lblFoto.setText("Sem foto");
        lblFoto.setIcon(null);
        lblFoto.setHorizontalAlignment(
                javax.swing.SwingConstants.CENTER
        );

        if (caminho == null || caminho.isBlank()) {
            return;
        }

        File arquivo = new File(caminho);

        if (!arquivo.exists()) {
            System.out.println("Foto não encontrada: " + caminho);
            return;
        }

        ImageIcon original = new ImageIcon(caminho);

        Image imagem = original.getImage().getScaledInstance(
                190, 115, Image.SCALE_SMOOTH
        );

        lblFoto.setIcon(new ImageIcon(imagem));
        lblFoto.setText("");
    }

