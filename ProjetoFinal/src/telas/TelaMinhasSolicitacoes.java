    private void carregarSolicitacao() {

        DefaultTableModel modelo
                = (DefaultTableModel) tblSolicitacoes.getModel();

        modelo.setRowCount(0);
        tblSolicitacoes.setRowSorter(null);

        if (usuario == null || !"CLIENTE".equals(usuario.getPerfil())) {
            return;
        }

        SolicitacaoDAO dao = new SolicitacaoDAO();
        AnimalDAO animalDAO = new AnimalDAO();

        ArrayList<Solicitacao> lista
                = dao.consultarPorCliente(usuario.getIdPessoa());

        int pendentes = 0;
        int aprovadas = 0;
        int recusadas = 0;

        for (Solicitacao s : lista) {

            Animal animal = animalDAO.consultarPorId(s.getIdAnimal());

            String nomeAnimal = animal != null
                    ? animal.getNomeAnimal()
                    : "Animal não encontrado";

            modelo.addRow(new Object[]{
                s.getIdSolicitacao(),
                nomeAnimal,
                s.getDataSolicitacao().toString(),
                s.getStatus()
            });

            if ("Pendente".equals(s.getStatus())) {
                pendentes++;
            } else if ("Aprovada".equals(s.getStatus())) {
                aprovadas++;
            } else if ("Recusada".equals(s.getStatus())) {
                recusadas++;
            }
        }

        lblPendentes.setText(String.valueOf(pendentes));
        lblAprovadas.setText(String.valueOf(aprovadas));
        lblRecusadas.setText(String.valueOf(recusadas));
    }

    private void filtrarSolicitacoes(String status) {

        DefaultTableModel modelo
                = (DefaultTableModel) tblSolicitacoes.getModel();

        TableRowSorter<DefaultTableModel> sorter
                = new TableRowSorter<>(modelo);

        tblSolicitacoes.setRowSorter(sorter);

        sorter.setRowFilter(
                RowFilter.regexFilter("(?i)^" + status + "$", 3)
        );
    }

